/// Turn on durable ingest buffering with the default bounds (72 h window, 5 GiB cap, directory
/// `.datahub-spool` under the working directory unless `datahub_config_set_buffer_dir` says
/// otherwise). Off by default.
#[no_mangle]
pub unsafe extern "C" fn datahub_config_enable_buffering(
    config: *mut datahub_config,
) -> datahub_status {
    guard(|| {
        let config = ffi_try!(mut_arg(config, "config"));
        config.set("ENABLE_BUFFERING", "true");
        datahub_status::DATAHUB_OK
    })
}

/// Directory for the on-disk spools. Also enables buffering: a host that names a spool directory
/// wants the spool.
#[no_mangle]
pub unsafe extern "C" fn datahub_config_set_buffer_dir(
    config: *mut datahub_config,
    dir: *const c_char,
) -> datahub_status {
    guard(|| {
        let config = ffi_try!(mut_arg(config, "config"));
        let dir = ffi_try!(str_arg(dir, "dir"));
        config.set("BUFFER_DIR", dir);
        config.set("ENABLE_BUFFERING", "true");
        datahub_status::DATAHUB_OK
    })
}

/// How long spooled records are kept, in seconds, measured on each record's own timestamp
/// (default 72 h). Also enables buffering.
#[no_mangle]
pub unsafe extern "C" fn datahub_config_set_buffer_retention_secs(
    config: *mut datahub_config,
    seconds: i64,
) -> datahub_status {
    guard(|| {
        let config = ffi_try!(mut_arg(config, "config"));
        if seconds <= 0 {
            return fail(
                datahub_status::DATAHUB_INVALID_ARGUMENT,
                0,
                "buffer retention must be a positive number of seconds",
            );
        }
        config.set("BUFFER_RETENTION_SECS", &seconds.to_string());
        config.set("ENABLE_BUFFERING", "true");
        datahub_status::DATAHUB_OK
    })
}

/// Size cap for each spool in bytes; the oldest segment is dropped past it (default 5 GiB).
/// Also enables buffering.
#[no_mangle]
pub unsafe extern "C" fn datahub_config_set_buffer_max_bytes(
    config: *mut datahub_config,
    bytes: u64,
) -> datahub_status {
    guard(|| {
        let config = ffi_try!(mut_arg(config, "config"));
        if bytes == 0 {
            return fail(
                datahub_status::DATAHUB_INVALID_ARGUMENT,
                0,
                "buffer size cap must be positive",
            );
        }
        config.set("BUFFER_MAX_BYTES", &bytes.to_string());
        config.set("ENABLE_BUFFERING", "true");
        datahub_status::DATAHUB_OK
    })
}

/// Release a config. The client it was used to build keeps its own copy. NULL is ignored.
#[no_mangle]
pub unsafe extern "C" fn datahub_config_free(config: *mut datahub_config) {
    if !config.is_null() {
        drop(Box::from_raw(config));
    }
}

/// The value of a key, for the rest of the crate.
pub(crate) unsafe fn config_value<'a>(
    config: *const datahub_config,
    key: &str,
) -> Result<Option<&'a str>, datahub_status> {
    Ok(ref_arg(config, "config")?.get(key))
}

#[cfg(test)]
mod tests {
    use super::parse_env_text;

    #[test]
    fn parses_the_dotenv_subset_this_project_uses() {
        let text = "# comment\n\nBASE_URL=https://h\nexport TOKEN='a b'\nSCOPE=\"organization:*\" # tenant\nX = plain # note\nY=\n";
        let entries = parse_env_text(text).unwrap();
        assert_eq!(
            entries,
            vec![
                ("BASE_URL".to_string(), "https://h".to_string()),
                ("TOKEN".to_string(), "a b".to_string()),
                ("SCOPE".to_string(), "organization:*".to_string()),
                ("X".to_string(), "plain".to_string()),
                ("Y".to_string(), String::new()),
            ]
        );
    }

    #[test]
    fn rejects_what_it_cannot_read_and_names_the_line() {
        assert_eq!(
            parse_env_text("A=1\nnot a pair\n").unwrap_err(),
            "line 2: expected KEY=value"
        );
        assert_eq!(
            parse_env_text("BAD KEY=1\n").unwrap_err(),
            "line 1: \"BAD KEY\" is not a valid key"
        );
        assert_eq!(
            parse_env_text("A=\"open\n").unwrap_err(),
            "line 1: unterminated quote"
        );
    }
}
