/// OAuth2 client credentials: the token endpoint mints and refreshes tokens with these. All three
/// are required for the flow to be configured at all.
#[no_mangle]
pub unsafe extern "C" fn datahub_config_set_client_credentials(
    config: *mut datahub_config,
    client_id: *const c_char,
    client_secret: *const c_char,
    token_uri: *const c_char,
) -> datahub_status {
    guard(|| {
        let config = ffi_try!(mut_arg(config, "config"));
        let client_id = ffi_try!(str_arg(client_id, "client_id"));
        let client_secret = ffi_try!(str_arg(client_secret, "client_secret"));
        let token_uri = ffi_try!(str_arg(token_uri, "token_uri"));
        config.set("CLIENT_ID", client_id);
        config.set("CLIENT_SECRET", client_secret);
        config.set("TOKEN_URI", token_uri);
        datahub_status::DATAHUB_OK
    })
}

