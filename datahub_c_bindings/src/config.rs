//! `datahub_config`: the values a client is built from.
//!
//! A config is a map keyed by the same names the environment uses (`BASE_URL`, `TOKEN`,
//! `CLIENT_ID`, …, `BUFFER_DIR`), so the environment, an env file and the typed setters all feed
//! one code path: `DataHubConfig::from_map` in the core. Nothing here reads or writes the process
//! environment unless `datahub_config_from_env` is called, and nothing ever reads a `.env` file
//! from the working directory — a library must not pick up a dotfile from the host's cwd.
//!
//! Every export is written out by hand rather than generated by a macro: cbindgen does not expand
//! `macro_rules!`, so a macro-generated function would exist in the library but not in the header.

use std::collections::HashMap;
use std::env;
use std::ffi::c_char;
use std::path::Path;

use intellistream_datahub_sdk::datahub::DataHubConfig;
use intellistream_datahub_sdk::errors::DataHubError;

use crate::error::{datahub_status, fail, guard};
use crate::util::{mut_arg, opt_str_arg, ref_arg, str_arg};

/// Configuration for a `datahub_client`. Opaque; free with `datahub_config_free`.
pub struct datahub_config {
    pub(crate) values: HashMap<String, String>,
}

impl datahub_config {
    pub(crate) fn build(&self) -> Result<DataHubConfig, DataHubError> {
        DataHubConfig::from_map(self.values.clone())
    }

    pub(crate) fn get(&self, key: &str) -> Option<&str> {
        self.values.get(key).map(String::as_str)
    }

    fn set(&mut self, key: &str, value: &str) {
        self.values.insert(key.to_string(), value.to_string());
    }
}

/// A new, empty config. Never NULL.
#[no_mangle]
pub extern "C" fn datahub_config_new() -> *mut datahub_config {
    Box::into_raw(Box::new(datahub_config {
        values: HashMap::new(),
    }))
}

/// A config holding a snapshot of the process environment (every variable, so the usual
/// `BASE_URL`, `TOKEN`, `CLIENT_ID`, `BUFFER_DIR`, … are picked up). Never NULL. Does **not** read
/// a `.env` file; see `datahub_config_load_envfile`.
#[no_mangle]
pub extern "C" fn datahub_config_from_env() -> *mut datahub_config {
    Box::into_raw(Box::new(datahub_config {
        values: env::vars().collect(),
    }))
}

/// Parse dotenv-style text: one `KEY=value` per line, `#` comments, blank lines, an optional
/// `export ` prefix, and single or double quotes around a value. Nothing fancier — the same
/// subset every `.env` in this project uses.
pub(crate) fn parse_env_text(text: &str) -> Result<Vec<(String, String)>, String> {
    let mut entries = Vec::new();
    for (index, raw) in text.lines().enumerate() {
        let number = index + 1;
        let line = raw.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let line = line.strip_prefix("export ").unwrap_or(line).trim_start();
        let Some((key, value)) = line.split_once('=') else {
            return Err(format!("line {number}: expected KEY=value"));
        };
        let key = key.trim();
        if key.is_empty() || !key.chars().all(|c| c.is_ascii_alphanumeric() || c == '_') {
            return Err(format!("line {number}: {key:?} is not a valid key"));
        }
        let value = value.trim();
        let value = match value.chars().next() {
            Some(quote @ ('"' | '\'')) => match value[1..].find(quote) {
                Some(end) => &value[1..1 + end],
                None => return Err(format!("line {number}: unterminated quote")),
            },
            _ => value.split(" #").next().unwrap_or(value).trim(),
        };
        entries.push((key.to_string(), value.to_string()));
    }
    Ok(entries)
}

/// Read a dotenv-style file (`KEY=value` lines) into the config, overriding any keys already
/// set. The process environment is left untouched. `DATAHUB_IO` when the file cannot be read,
/// `DATAHUB_INVALID_ARGUMENT` when a line does not parse.
#[no_mangle]
pub unsafe extern "C" fn datahub_config_load_envfile(
    config: *mut datahub_config,
    path: *const c_char,
) -> datahub_status {
    guard(|| {
        let config = ffi_try!(mut_arg(config, "config"));
        let path = ffi_try!(str_arg(path, "path"));
        let text = match std::fs::read_to_string(Path::new(path)) {
            Ok(text) => text,
            Err(e) => {
                return fail(
                    datahub_status::DATAHUB_IO,
                    0,
                    format!("cannot read env file {path}: {e}"),
                )
            }
        };
        match parse_env_text(&text) {
            Ok(entries) => {
                for (key, value) in entries {
                    config.set(&key, &value);
                }
                datahub_status::DATAHUB_OK
            }
            Err(e) => fail(
                datahub_status::DATAHUB_INVALID_ARGUMENT,
                0,
                format!("cannot parse env file {path}: {e}"),
            ),
        }
    })
}

/// Set any configuration key by its environment name (`SCOPE`, `AUDIENCE`, `ASSERTION_GRANT`, …).
/// The typed setters below are conveniences over this. A NULL value removes the key.
#[no_mangle]
pub unsafe extern "C" fn datahub_config_set(
    config: *mut datahub_config,
    key: *const c_char,
    value: *const c_char,
) -> datahub_status {
    guard(|| {
        let config = ffi_try!(mut_arg(config, "config"));
        let key = ffi_try!(str_arg(key, "key"));
        if key.trim().is_empty() {
            return fail(
                datahub_status::DATAHUB_INVALID_ARGUMENT,
                0,
                "key must not be empty",
            );
        }
        match ffi_try!(opt_str_arg(value, "value")) {
            Some(value) => config.set(key, value),
            None => {
                config.values.remove(key);
            }
        }
        datahub_status::DATAHUB_OK
    })
}

thread_local! {
    /// `datahub_config_get` hands out NUL-terminated copies; they live here so the pointer stays
    /// valid until the same key is read again on this thread, or the thread ends.
    static GET_CACHE: std::cell::RefCell<HashMap<String, std::ffi::CString>> =
        std::cell::RefCell::new(HashMap::new());
}

/// Read a key back, or NULL when it is unset. Borrowed; valid until the same key is read again
/// on this thread. Meant for diagnostics, not for hot paths.
#[no_mangle]
pub unsafe extern "C" fn datahub_config_get(
    config: *const datahub_config,
    key: *const c_char,
) -> *const c_char {
    let (Some(config), false) = (config.as_ref(), key.is_null()) else {
        return std::ptr::null();
    };
    let Ok(key) = std::ffi::CStr::from_ptr(key).to_str() else {
        return std::ptr::null();
    };
    match config.values.get(key) {
        Some(value) => GET_CACHE.with(|cache| {
            let mut cache = cache.borrow_mut();
            cache.insert(key.to_string(), crate::util::to_cstring(value));
            cache[key].as_ptr()
        }),
        None => std::ptr::null(),
    }
}

/// The body every typed string setter shares.
unsafe fn set_key(config: *mut datahub_config, key: &str, value: *const c_char) -> datahub_status {
    guard(|| {
        let config = ffi_try!(mut_arg(config, "config"));
        let value = ffi_try!(str_arg(value, "value"));
        config.set(key, value);
        datahub_status::DATAHUB_OK
    })
}

/// The api's root URL, e.g. `https://datahub.example.com`. Required.
#[no_mangle]
pub unsafe extern "C" fn datahub_config_set_base_url(
    config: *mut datahub_config,
    value: *const c_char,
) -> datahub_status {
    set_key(config, "BASE_URL", value)
}

